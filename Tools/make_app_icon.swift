func color(_ hex: UInt32, _ a: CGFloat = 1) -> NSColor {
    NSColor(srgbRed: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,
            blue: CGFloat(hex & 0xFF) / 255, alpha: a)
}

/// The icon's body: a superellipse, close to macOS's continuous corners.
func squircle(in rect: NSRect) -> NSBezierPath {
    let path = NSBezierPath()
    let steps = 240
    for i in 0..<steps {
        let t = 2 * CGFloat.pi * CGFloat(i) / CGFloat(steps)
        let c = cos(t), s = sin(t)
        let x = rect.midX + rect.width / 2 * copysign(pow(abs(c), 0.4), c)
        let y = rect.midY + rect.height / 2 * copysign(pow(abs(s), 0.4), s)
        i == 0 ? path.move(to: NSPoint(x: x, y: y)) : path.line(to: NSPoint(x: x, y: y))
    }
    path.close()
    return path
}

/// A path from "x y x y …" in the design's y-down, 1024-unit coordinates.
func polyline(_ points: String, k: CGFloat, closed: Bool) -> NSBezierPath {
    let v = points.split(whereSeparator: \.isWhitespace).map { CGFloat(Double($0)!) }
    let path = NSBezierPath()
    for i in stride(from: 0, to: v.count, by: 2) {
        let p = NSPoint(x: v[i] * k, y: (1024 - v[i + 1]) * k)
        i == 0 ? path.move(to: p) : path.line(to: p)
    }
    if closed { path.close() }
    return path
}

func render(px: Int) -> NSBitmapImageRep {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: px, pixelsHigh: px, bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                               colorSpaceName: .calibratedRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    rep.size = NSSize(width: px, height: px)
    NSGraphicsContext.saveGraphicsState()
    let ctx = NSGraphicsContext(bitmapImageRep: rep)!
    NSGraphicsContext.current = ctx
    ctx.imageInterpolation = .high
    let k = CGFloat(px) / 1024
    // Body on the macOS grid; y-up coordinates.
    let body = NSRect(x: 100 * k, y: 100 * k, width: 824 * k, height: 824 * k)
    let shape = squircle(in: body)

    // Drop shadow under the body (skipped at the tiniest sizes, where it muddies).
    if px >= 64 {
        NSGraphicsContext.saveGraphicsState()
        let shadow = NSShadow()
        shadow.shadowOffset = NSSize(width: 0, height: -10 * k)
        shadow.shadowBlurRadius = 22 * k
        shadow.shadowColor = NSColor.black.withAlphaComponent(0.26)
        shadow.set()
        color(0xF4EEE2).setFill()
        shape.fill()
        NSGraphicsContext.restoreGraphicsState()
    }

    NSGraphicsContext.saveGraphicsState()
    shape.addClip()
    // Paper, with a soft highlight over the top, under the ink.
    color(0xF4EEE2).setFill()
    body.fill()
    let glossRect = NSRect(x: body.minX, y: body.maxY - body.height * 0.40, width: body.width, height: body.height * 0.40)
    NSGradient(starting: NSColor.white.withAlphaComponent(0), ending: NSColor.white.withAlphaComponent(0.12))!
        .draw(in: glossRect, angle: 90)

    // The stroke.
    let ink = color(0x1E1C19)
    let enso = polyline(ensoOutline, k: k, closed: true)
    ink.set()
    enso.fill()
    let extra: CGFloat = px <= 16 ? 34 : px <= 32 ? 20 : px <= 64 ? 8 : 0
    if extra > 0 {
        enso.lineWidth = extra * k
        enso.lineJoinStyle = .round
        enso.stroke()
    } else {
        color(0xF4EEE2).setStroke()
        for (width, points) in ensoStreaks {
            let streak = polyline(points, k: k, closed: false)
            streak.lineWidth = width * k
            streak.lineCapStyle = .round
            streak.stroke()
        }
    }

    NSGraphicsContext.restoreGraphicsState()

    // Hairline edge.
    let edge = squircle(in: body.insetBy(dx: 0.75 * k, dy: 0.75 * k))
    edge.lineWidth = max(0.5, 1.5 * k)
    NSColor.black.withAlphaComponent(0.07).setStroke()
    edge.stroke()

    NSGraphicsContext.restoreGraphicsState()
    return rep
}

